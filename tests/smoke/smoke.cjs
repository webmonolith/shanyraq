// Runs the built CJS output on any Node >= 18 without dev dependencies.
const assert = require('node:assert/strict')
const { getMessage, isValidTaxId } = require('shanyraq')
const { isValidBIN } = require('shanyraq/bin')
const { isWorkingDay } = require('shanyraq/calendar')
const { parseDate } = require('shanyraq/date')
const { createFaker } = require('shanyraq/faker')
const { en } = require('shanyraq/i18n')
const { isValidIBAN } = require('shanyraq/iban')
const { isValidIIN } = require('shanyraq/iin')
const { vacationPay } = require('shanyraq/leave')
const { loanSchedule } = require('shanyraq/loan')
const { moneyToWords } = require('shanyraq/money')
const { isValidPhone } = require('shanyraq/phone')
const { isValidPlate } = require('shanyraq/plate')
const { REGIONS } = require('shanyraq/regions')
const { toLatin } = require('shanyraq/translit')

assert.equal(getMessage('en', 'iban', 'length'), en.iban.length)
assert.equal(isValidIIN('900101300126'), true)
assert.equal(vacationPay(3600000, '2026-07-01').value.end, '2026-07-25')
assert.equal(loanSchedule(1000000, 20, 12).value.monthly, 92634.51)
assert.equal(isValidBIN('180340021791'), true)
assert.equal(isValidTaxId('900101300126'), true)
assert.equal(isValidPhone('+7 707 123 45 67'), true)
assert.equal(moneyToWords(2).value, 'Два теңге 00 тиынов')
assert.equal(isValidBIN(createFaker(2).bin(), { strict: true }), true)
assert.equal(isValidIBAN('KZ86125KZT5004100100'), true)
assert.equal(isValidPlate('389 BK 01', { strict: true }), true)
assert.equal(REGIONS.length, 20)
assert.equal(isWorkingDay('2024-05-04'), true)
assert.equal(parseDate('22 октября 2026 года').value.iso, '2026-10-22')
assert.equal(toLatin('Шымкент', { scheme: '2018' }), 'Shymkent')
console.log(`cjs ok (node ${process.version})`)

export interface Page extends Text {
  path: string
  lang: Lang
  kind: 'tool' | 'hub' | 'root' | 'notFound'
  tool?: ToolId
  /** Same page in every language; absent for pages outside the language tree. */
  alternates?: Record<Lang, string>
}

export const toolPath = (lang: Lang, id: ToolId): string =>
  `/${lang}/${TOOLS.find((t) => t.id === id)?.slug[lang]}/`

export const hubPath = (lang: Lang): string => `/${lang}/`

const hubAlternates = { ru: hubPath('ru'), kk: hubPath('kk') }

export const pages: Page[] = [
  { ...HUB.ru, path: '/', lang: 'ru', kind: 'root' },
  ...LANGS.flatMap((lang): Page[] => [
    { ...HUB[lang], path: hubPath(lang), lang, kind: 'hub', alternates: hubAlternates },
    ...TOOLS.map(
      (t): Page => ({
        ...t.text[lang],
        path: toolPath(lang, t.id),
        lang,
        kind: 'tool',
        tool: t.id,
        alternates: { ru: toolPath('ru', t.id), kk: toolPath('kk', t.id) },
      }),
    ),
  ]),
]

export const notFound = (path: string): Page => {
  const lang: Lang = path.startsWith('/kk/') ? 'kk' : 'ru'
  return { ...NOT_FOUND[lang], path, lang, kind: 'notFound' }
}

export const pageByPath = (path: string): Page =>
  pages.find((p) => p.path === path) ?? notFound(path)

export const ogName = (page: Page): string =>
  page.kind === 'root' ? 'home' : page.path.slice(1, -1).replace(/\//g, '-')

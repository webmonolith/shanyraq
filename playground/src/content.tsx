// Server-only page text. Every statement here restates data/*.json; the page lists the sources.

import type { ReactNode } from 'react'
import { REGIONS } from 'shanyraq/regions'
import banks from '../../data/banks.json'
import plates from '../../data/plates.json'
import type { Lang, ToolId } from './site'

type Content = (props: { lang: Lang }) => ReactNode

const both =
  (ru: ReactNode, kk: ReactNode): Content =>
  ({ lang }) =>
    lang === 'ru' ? ru : kk

const activeBanks = banks.banks.filter((b) => b.active).sort((a, b) => a.code.localeCompare(b.code))

const FILTER = { ru: 'Поиск по таблице', kk: 'Кесте бойынша іздеу' }

// Hidden until entry-client wires it up, so there is no dead input without JS.
const Filter = ({ lang }: { lang: Lang }) => (
  <input
    className="filter"
    type="search"
    placeholder={FILTER[lang]}
    aria-label={FILTER[lang]}
    hidden
  />
)

const BankTable: Content = ({ lang }) => (
  <div className="table" data-filter>
    <Filter lang={lang} />
    <table>
      <thead>
        <tr>
          <th>{lang === 'ru' ? 'Код' : 'Код'}</th>
          <th>{lang === 'ru' ? 'БИК' : 'БСК'}</th>
          <th>{lang === 'ru' ? 'Банк' : 'Банк'}</th>
        </tr>
      </thead>
      <tbody>
        {activeBanks.map((b) => (
          <tr key={b.code + b.bic}>
            <td>{b.code}</td>
            <td>
              <code>{b.bic}</code>
            </td>
            <td>{lang === 'ru' ? b.nameRu : b.nameKk}</td>
          </tr>
        ))}
      </tbody>
    </table>
  </div>
)

const RegionTable: Content = ({ lang }) => (
  <div className="table" data-filter>
    <Filter lang={lang} />
    <table>
      <thead>
        <tr>
          <th>{lang === 'ru' ? 'Код' : 'Код'}</th>
          <th>{lang === 'ru' ? 'Регион' : 'Өңір'}</th>
          <th>{lang === 'ru' ? 'Центр' : 'Орталығы'}</th>
        </tr>
      </thead>
      <tbody>
        {[...REGIONS]
          .sort((a, b) => a.plateCode.localeCompare(b.plateCode))
          .map((r) => (
            <tr key={r.id}>
              <td>{r.plateCode}</td>
              <td>{r.name[lang]}</td>
              <td>{r.center}</td>
            </tr>
          ))}
      </tbody>
    </table>
  </div>
)

const plateExamples = plates.formats.filter(
  (f, i) => plates.formats.findIndex((g) => g.example === f.example) === i,
)

const PlateTable: Content = ({ lang }) => (
  <div className="table">
    <table>
      <thead>
        <tr>
          <th>{lang === 'ru' ? 'Образец' : 'Үлгі'}</th>
          <th>{lang === 'ru' ? 'Тип по приказу № 1040' : '№ 1040 бұйрық бойынша түрі'}</th>
        </tr>
      </thead>
      <tbody>
        {plateExamples.map((p) => (
          <tr key={p.example}>
            <td>
              <code>{p.example}</code>
            </td>
            <td lang="ru">{p.plateType}</td>
          </tr>
        ))}
      </tbody>
    </table>
  </div>
)


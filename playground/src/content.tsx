type Row = (number | null)[]
const comma = (v: number) => n(v).replace('.', ',')
// Brackets in data/vehicle.json are upper bounds; null = no upper bound.
const ranges = (rows: Row[], unit: string, lang: Lang, step = 1) =>
  rows.map(([up], i) => {
    const low = i ? (rows[i - 1]?.[0] as number) : null
    if (low === null)
      return lang === 'ru'
        ? `до ${comma(up as number)} ${unit}`
        : `${comma(up as number)} ${unit} дейін`
    if (up === null)
      return lang === 'ru' ? `свыше ${comma(low)} ${unit}` : `${comma(low)} ${unit} жоғары`
    return `${comma(low + step)}–${comma(up as number)} ${unit}`
  })

// Age wording of Tax Code art. 615 p. 4: «до 2 лет», «от 2 до 3 лет», «от 3 лет и выше».
const ages = (rows: Row[], lang: Lang) =>
  rows.map(([up], i) => {
    const low = i ? (rows[i - 1]?.[0] as number) : null
    if (lang === 'kk') {
      if (low === null) return `${up} жасқа дейін`
      return up === null ? `${low} жастан бастап` : `${low}–${up} жас`
    }
    if (low === null) return `до ${up} лет`
    return up === null ? `от ${low} лет и выше` : `от ${low} до ${up} лет`
  })


interface RegionsData {
  regions: {
    id: string
    kind: string
    nameRu: string
    nameKk: string
    nameEn: string
    center: string
    plateCode: string
    katoPrefix: string
    katoCode: string
  }[]
}

const regions = read<RegionsData>('regions').regions.sort((a, b) =>
  a.plateCode.localeCompare(b.plateCode),
)
regions.forEach((r, i) => {
  if (Number(r.plateCode) !== i + 1) throw new Error(`Plate codes are not 01…n: ${r.plateCode}`)
})

write(
  'regions/generated.ts',
  'data/regions.json',
  `import type { Region } from './types'

/** Region ids in plate code order: index 0 is plate code 01. */
export const BY_PLATE_CODE = ${json(regions.map((r) => r.id))} as const

export const REGIONS: readonly Region[] = ${json(
    regions.map((r) => ({
      id: r.id,
      kind: r.kind,
      name: { ru: r.nameRu, kk: r.nameKk, en: r.nameEn },
      center: r.center,
      plateCode: r.plateCode,
      katoPrefix: r.katoPrefix,
      katoCode: r.katoCode,
    })),
  )}
`,
)

interface CalendarHoliday {
  id: string
  month: number | null
  day: number | null
  durationDays: number
  nameRu: string
  nameKk: string
  nameEn: string
  type: string
  weekendShift: boolean
  since?: string
}

interface CalendarData {
  holidays: CalendarHoliday[]
  removed: { id: string; month: number; day: number; until: string }[]
  kurbanAit: Record<string, { date: string }>
  transfers: Record<string, { days: { from: string; to: string }[] }>
}

const calendar = read<CalendarData>('calendar')

// 16 December was a day off before 2022 too (first of two days); its `since` marks the new wording only.
const SINCE_IGNORED = new Set(['independence-day'])

const since = (s?: string) => (s && s.length === 4 ? `${s}-01-01` : s)
// `until: '2022'` means the day was dropped during 2022 and was last a day off in 2021.
const until = (s: string) => (s.length === 4 ? `${Number(s) - 1}-12-31` : s)

const holiday = (h: CalendarHoliday, from = '', to = '') => [
  h.id,
  h.month ?? 0,
  h.day ?? 0,
  h.durationDays,
  h.type,
  h.weekendShift ? 1 : 0,
  from,
  to,
  h.nameRu,
  h.nameKk,
  h.nameEn,
]

const holidays = [
  ...calendar.holidays.map((h) =>
    holiday(h, SINCE_IGNORED.has(h.id) ? '' : (since(h.since) ?? '')),
  ),
  ...calendar.removed.map((r) => {
    const base = calendar.holidays.find((h) => r.id.startsWith(`${h.id}-`))
    if (!base) throw new Error(`No current holiday for removed ${r.id}`)
    return holiday({ ...base, month: r.month, day: r.day, durationDays: 1 }, '', until(r.until))
  }),
]

write(
  'calendar/generated.ts',
  'data/calendar.json',
  `import type { HolidayId, HolidayType } from './types'

/** [id, month, day (0 = by KURBAN_AIT), days, type, weekend shift, since, until, ru, kk, en] */
export const HOLIDAYS: [HolidayId, number, number, number, HolidayType, 0 | 1, string, string, string, string, string][] = ${json(holidays)}

export const KURBAN_AIT: Record<number, string> = ${json(
    Object.fromEntries(Object.entries(calendar.kurbanAit).map(([y, k]) => [y, k.date])),
  )}

/** [from (becomes a working day), to (becomes a day off)] by Labour Ministry orders. */
export const TRANSFERS: Record<number, [string, string][]> = ${json(
    Object.fromEntries(
      Object.entries(calendar.transfers).map(([y, t]) => [y, t.days.map((d) => [d.from, d.to])]),
    ),
  )}
`,
)

interface TranslitData {
  map: { cyr: string; lat: string; latLower: string }[]
  otherSchemes: { '2018': { officialTable: string; conventionForMissing: Record<string, string> } }
}

const translit = read<TranslitData>('translit-2021')

const scheme2021 = Object.fromEntries(translit.map.map((m) => [m.cyr, [m.lat, m.latLower]]))

const scheme2018: Record<string, [string, string]> = {}
for (const row of translit.otherSchemes['2018'].officialTable.split('; ')) {
  const m = /^\d+ (\S+) (\S+) (.+)$/.exec(row)
  if (!m) throw new Error(`Bad 2018 table row: ${row}`)
  for (const cyr of (m[3] as string).split(', '))
    scheme2018[cyr.toUpperCase()] = [m[1] as string, m[2] as string]
}
for (const [cyr, value] of Object.entries(translit.otherSchemes['2018'].conventionForMissing)) {
  const upper = value.split(' ')[0] as string
  // TODO(verify): Ё/Ю/Я start with the Й sound, which is ı in 2018; the source gives capitals only.
  scheme2018[cyr] = [upper, upper.replace(/^I/, 'ı').toLowerCase()]
}

const missing = Object.keys(scheme2021).filter((c) => !scheme2018[c])
if (missing.length) throw new Error(`2018 scheme lacks ${missing.join(' ')}`)

write(
  'translit/generated.ts',
  'data/translit-2021.json',
  `/** Cyrillic capital → [Latin capital, Latin small]. */
export const SCHEMES: Record<'2021' | '2018', Record<string, [string, string]>> = ${json({ 2021: scheme2021, 2018: scheme2018 })}
`,
)

interface TaxData {
  years: Record<string, { mrp: number; mzp: number }>
  ipn: { rate: number; highRate: number; thresholdMrp: number; baseDeductionMrp: number }
  opv: { rate: number; maxMzp: number }
  opvr: { rates: Record<string, number>; minMzp: number; maxMzp: number }
  so: { rate: number; minMzp: number; maxMzp: number }
  vosms: { rate: number; maxMzp: number }
  oosms: { rate: number; maxMzp: number }
  sn: { rate: number; minMrp: number }
  vat: { rate: number; registrationThresholdMrp: number }
  simplified: {
    rate: number
    maxChange: number
    incomeLimitMrp: number
    self: {
      opv: { rate: number; maxMzp: number }
      so: { rate: number; minMzp: number; maxMzp: number }
      vosms: { rate: number; baseMzp: number }
    }
  }
}

const tax = read<TaxData>('tax')
const pct = (n: number) => Math.round(n * 10) / 1000

const taxYears = Object.fromEntries(
  Object.entries(tax.years).map(([y, v]) => {
    const opvr = tax.opvr.rates[y]
    if (opvr === undefined) throw new Error(`data/tax.json: no ОПВР rate for ${y}`)
    return [y, { mrp: v.mrp, mzp: v.mzp, opvr: pct(opvr) }]
  }),
)

write(
  'tax/generated.ts',
  'data/tax.json',
  `/** MRP, MZP (tenge) and the employer pension rate that changes every year. */
export const YEARS: Record<number, { mrp: number; mzp: number; opvr: number }> = ${json(taxYears)}

/** Rates as fractions; limits in MRP or MZP of the year. */
export const RATES = ${json({
    ipn: pct(tax.ipn.rate),
    ipnHigh: pct(tax.ipn.highRate),
    ipnThresholdMrp: tax.ipn.thresholdMrp,
    baseDeductionMrp: tax.ipn.baseDeductionMrp,
    opv: pct(tax.opv.rate),
    opvMaxMzp: tax.opv.maxMzp,
    opvrMinMzp: tax.opvr.minMzp,
    opvrMaxMzp: tax.opvr.maxMzp,
    so: pct(tax.so.rate),
    soMinMzp: tax.so.minMzp,
    soMaxMzp: tax.so.maxMzp,
    vosms: pct(tax.vosms.rate),
    vosmsMaxMzp: tax.vosms.maxMzp,
    oosms: pct(tax.oosms.rate),
    oosmsMaxMzp: tax.oosms.maxMzp,
    sn: pct(tax.sn.rate),
    snMinMrp: tax.sn.minMrp,
    vat: pct(tax.vat.rate),
    vatThresholdMrp: tax.vat.registrationThresholdMrp,
    simplified: pct(tax.simplified.rate),
    simplifiedMaxChange: pct(tax.simplified.maxChange),
    simplifiedLimitMrp: tax.simplified.incomeLimitMrp,
    selfOpv: pct(tax.simplified.self.opv.rate),
    selfOpvMaxMzp: tax.simplified.self.opv.maxMzp,
    selfSo: pct(tax.simplified.self.so.rate),
    selfSoMinMzp: tax.simplified.self.so.minMzp,
    selfSoMaxMzp: tax.simplified.self.so.maxMzp,
    selfVosms: pct(tax.simplified.self.vosms.rate),
    selfVosmsBaseMzp: tax.simplified.self.vosms.baseMzp,
  })} as const
`,
)


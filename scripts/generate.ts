// Turns data/*.json into src/**/generated.ts. Run: npm run generate
import { readFileSync, writeFileSync } from 'node:fs'

interface PhoneData {
  countryRanges: {
    kazakhstanExclusive: string[]
    russiaExclusive: string[]
    shared: string[]
    kazakhstanInUse2022: { geographicABC: string; otherNonGeographic: { code: string }[] }
  }
  mobile: { code: string; originalOperator: string }[]
  landline: { areaCode: string; nsnPattern: string; city: string; cityKk: string; cityEn: string }[]
}

const OPERATORS: [match: string, id: string][] = [
  ['Кселл', 'kcell'],
  ['КаР-Тел', 'beeline'],
  ['Мобайл Телеком-Сервис', 'tele2-altel'],
]

const read = <T>(name: string): T =>
  JSON.parse(readFileSync(new URL(`../data/${name}.json`, import.meta.url), 'utf8'))

const ranges = (list: string[]): number[][] =>
  list.map((r) => {
    const [lo, hi = lo] = r.split('-').map(Number)
    return [lo as number, hi as number]
  })

const write = (path: string, source: string, body: string) => {
  const header = `// Generated by scripts/generate.ts from ${source}. Do not edit.\n`
  writeFileSync(new URL(`../src/${path}`, import.meta.url), header + body)
  console.log(`wrote src/${path}`)
}

const phone = read<PhoneData>('phone')

const operator = (name: string): string => {
  const hit = OPERATORS.find(([match]) => name.includes(match))
  if (!hit) throw new Error(`Unknown operator in data/phone.json: ${name}`)
  return hit[1]
}

const geographic = [
  ...phone.countryRanges.kazakhstanInUse2022.geographicABC.matchAll(/(\d{3})-(\d{3})/g),
].map((m) => [Number(m[1]), Number(m[2])])

const landline = phone.landline
  .map((l) => {
    const next = /^\d+\[(\d+)\]/.exec(l.nsnPattern)?.[1] ?? ''
    if (!l.nsnPattern.startsWith(l.areaCode)) throw new Error(`Bad nsnPattern: ${l.nsnPattern}`)
    return [l.areaCode, next, l.city, l.cityKk, l.cityEn]
  })
  .sort((a, b) => (b[0] as string).length - (a[0] as string).length)

// biome format (npm run generate) turns this into single quotes and bare keys.
const json = (value: unknown) => JSON.stringify(value)

write(
  'phone/generated.ts',
  'data/phone.json',
  `import type { Operator } from './types'

export const KZ_RANGES = ${json(ranges(phone.countryRanges.kazakhstanExclusive))}
export const RU_RANGES = ${json(ranges(phone.countryRanges.russiaExclusive))}
export const SHARED_RANGES = ${json(ranges(phone.countryRanges.shared))}
export const GEOGRAPHIC_RANGES = ${json(geographic)}
export const OTHER_CODES = ${json(phone.countryRanges.kazakhstanInUse2022.otherNonGeographic.map((o) => o.code))}

export const MOBILE: Record<string, Operator> = ${json(Object.fromEntries(phone.mobile.map((m) => [m.code, operator(m.originalOperator)])))}

/** [areaCode, allowed next digits ('' = any), ru, kk, en], longest area code first. */
export const LANDLINE: [string, string, string, string, string][] = ${json(landline)}
`,
)

